export namespace main {
	
	export class ChatMessage {
	    role: string;
	    content: any;
	
	    static createFrom(source: any = {}) {
	        return new ChatMessage(source);
	    }
	
	    constructor(source: any = {}) {
	        if ('string' === typeof source) source = JSON.parse(source);
	        this.role = source["role"];
	        this.content = source["content"];
	    }
	}
	export class ChatCompletionRequest {
	    model: string;
	    messages: ChatMessage[];
	    temperature?: number;
	    stream?: boolean;
	    tools?: any;
	
	    static createFrom(source: any = {}) {
	        return new ChatCompletionRequest(source);
	    }
	
	    constructor(source: any = {}) {
	        if ('string' === typeof source) source = JSON.parse(source);
	        this.model = source["model"];
	        this.messages = this.convertValues(source["messages"], ChatMessage);
	        this.temperature = source["temperature"];
	        this.stream = source["stream"];
	        this.tools = source["tools"];
	    }
	
		convertValues(a: any, classs: any, asMap: boolean = false): any {
		    if (!a) {
		        return a;
		    }
		    if (a.slice && a.map) {
		        return (a as any[]).map(elem => this.convertValues(elem, classs));
		    } else if ("object" === typeof a) {
		        if (asMap) {
		            for (const key of Object.keys(a)) {
		                a[key] = new classs(a[key]);
		            }
		            return a;
		        }
		        return new classs(a);
		    }
		    return a;
		}
	}
	
	export class PendingRequestDTO {
	    id: string;
	    timestamp: string;
	    provider: string;
	    headers: Record<string, string>;
	    payload: ChatCompletionRequest;
	
	    static createFrom(source: any = {}) {
	        return new PendingRequestDTO(source);
	    }
	
	    constructor(source: any = {}) {
	        if ('string' === typeof source) source = JSON.parse(source);
	        this.id = source["id"];
	        this.timestamp = source["timestamp"];
	        this.provider = source["provider"];
	        this.headers = source["headers"];
	        this.payload = this.convertValues(source["payload"], ChatCompletionRequest);
	    }
	
		convertValues(a: any, classs: any, asMap: boolean = false): any {
		    if (!a) {
		        return a;
		    }
		    if (a.slice && a.map) {
		        return (a as any[]).map(elem => this.convertValues(elem, classs));
		    } else if ("object" === typeof a) {
		        if (asMap) {
		            for (const key of Object.keys(a)) {
		                a[key] = new classs(a[key]);
		            }
		            return a;
		        }
		        return new classs(a);
		    }
		    return a;
		}
	}

}

